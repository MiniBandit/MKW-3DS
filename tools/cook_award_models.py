#!/usr/bin/env python3
"""Cook original ceremony meshes and matching skeletal animation banks privately."""
import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
from cook_model import cook

ROOT=Path(__file__).resolve().parents[1]


def cook_one(job, source, output):
    resource, model, animated, index = job
    archive=source/resource
    prefix='award_'+re.sub('[^a-zA-Z0-9_]', '_', str(Path(resource).with_suffix('')))+'_'+str(index)
    exported=ROOT/'build/award-exports'/prefix
    exported.mkdir(parents=True,exist_ok=True)
    env={**os.environ,'MKW_RETAIL_LIGHTING':'1','MKW_FREEZE_NONLINEAR_UV':'1'}
    materials=None
    if resource.startswith('Demo/Trophy/'):
        env['MKW_MENU_MATERIALS']='1'
        env['MKW_AWARD_MATERIALS']='1'
        materials='models/'+prefix+'.dobj'
        (output/'models').mkdir(parents=True,exist_ok=True)
        env['MKW_OBJECT_BANK']=str((output/materials).resolve())
    if resource.startswith('unpacked/Award/') and 'v_stand' not in resource and 'shadow' not in resource:
        env['MKW_RACE_MATERIALS']='1'
    elif Path(resource).name in ('course_model.brres','vrcorn_model.brres'):
        env['MKW_COURSE_MATERIALS']='1'
        env['MKW_RETAIL_SKY']='1' if Path(resource).name=='vrcorn_model.brres' else '0'
    else:
        env['MKW_OBJECT_MATERIALS']='1'
    if (archive.parent/'course_model.brres').is_file() and archive.name!='course_model.brres':
        env['MKW_TEXTURE_SOURCES']=str(archive.parent/'course_model.brres')
    with (exported/'export.log').open('w') as log:
        subprocess.run(['node',str(ROOT/'build/export_brres.mjs'),str(archive),str(exported),model],
                       check=True,env=env,stdout=log,stderr=subprocess.STDOUT)
    portrait_atlas=ROOT/'build/mii-parts/retail-defaults/default-faces-atlas.png'
    staff_crowd=resource.startswith('unpacked/ending_demo/MiiObj')
    parts=cook(exported,output,prefix,256,preserve_vertices=animated,
               course_geometry=archive.name=='course_model.brres',
               texture_overrides={'Mii_Faces_dummy':portrait_atlas} if staff_crowd else None)
    bank=None
    if animated:
        if len(parts)!=1:raise ValueError('Animated ceremony model split: '+prefix)
        # Runtime palette skinning needs precisely the original model vertex order.
        bank='models/'+prefix+'.dskm'
        result=subprocess.run(['node',str(ROOT/'build/export_driver.mjs'),str(archive),str(output/bank),model],
                              check=True,capture_output=True,text=True)
        animation=json.loads(result.stdout)
        (exported/'animation.json').write_text(json.dumps(animation,indent=2)+'\n')
    print(prefix,flush=True)
    return {'resource':resource,'model':model,'prefix':prefix,'list':'models/'+prefix+'.list',
            'parts':[p['name'] for p in parts],'animation':bank,'materials':materials,
            'source_sha256':hashlib.sha256(archive.read_bytes()).hexdigest()}


def write_catalog(models):
    header=['// Generated by tools/cook_award_models.py from original ceremony archives.',
            '#pragma once','namespace mkw {',
            'struct AwardModelAsset {const char* archive;const char* model;const char* list;const char* animation;const char* materials;};',
            'inline constexpr AwardModelAsset AwardModelAssets[]={']
    for row in models:
        fields=[json.dumps(row[k]) for k in ('resource','model','list')]
        fields.append(json.dumps(row['animation']) if row['animation'] else 'nullptr')
        fields.append(json.dumps(row.get('materials')) if row.get('materials') else 'nullptr')
        header.append('{'+','.join(fields)+'},')
    header+=['};','}']
    (ROOT/'include/mkw/award_model_assets.hpp').write_text('\n'.join(header)+'\n')


def copy_collision(source,output):
    import shutil
    target=output/'models/award_winningrun_demo.kcl'
    target.parent.mkdir(parents=True,exist_ok=True)
    shutil.copyfile(source/'unpacked/winningrun_demo/course.kcl',target)
    for name in ('course','DemoCol'):
        target=output/'models'/('award_loser_demo'+('_DemoCol' if name=='DemoCol' else '')+'.kcl')
        target.parent.mkdir(parents=True,exist_ok=True)
        shutil.copyfile(source/'unpacked/loser_demo'/(name+'.kcl'),target)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source',type=Path,default=ROOT/'build/award-source')
    parser.add_argument('--output',type=Path,default=ROOT/'build/award-models')
    parser.add_argument('--jobs',type=int,default=4)
    parser.add_argument('--refresh-collision',action='store_true',
                        help='Refresh original ceremony KCL files and their existing receipt without re-cooking meshes')
    args=parser.parse_args()
    if args.refresh_collision:
        receipt_path=args.output/'award-models.json'
        receipt=json.loads(receipt_path.read_text())
        collision_names={'models/award_winningrun_demo.kcl','models/award_loser_demo.kcl',
                         'models/award_loser_demo_DemoCol.kcl'}
        # Do not bless unrelated stale/modified meshes merely because collision
        # resources were added. Their old receipt must still describe them.
        for name,digest in receipt['files'].items():
            if name not in collision_names:
                if hashlib.sha256((args.output/name).read_bytes()).hexdigest()!=digest:
                    raise ValueError('Existing ceremony receipt mismatch: '+name)
        copy_collision(args.source,args.output)
        for name in sorted(collision_names):
            receipt['files'][name]=hashlib.sha256((args.output/name).read_bytes()).hexdigest()
        receipt_path.write_text(json.dumps(receipt,indent=2)+'\n')
        print('Refreshed three original ceremony collision resources and receipt')
        return
    records=json.loads((args.source/'scene-bindings.json').read_text())['archives']
    jobs=[]
    for resource,record in records.items():
        for index,model in enumerate(record['models']):
            jobs.append((resource,model['name'],bool(record['skeletal']),index))
    args.output.mkdir(parents=True,exist_ok=True)
    with ThreadPoolExecutor(max_workers=max(1,args.jobs)) as pool:
        results=list(pool.map(lambda job:cook_one(job,args.source,args.output),jobs))
    copy_collision(args.source,args.output)
    write_catalog(results)
    from cook_award_environment import cook_environment
    cook_environment(args.source,results)
    from cook_award_effects import cook_effects
    cook_effects(args.source,args.output)
    files={p.relative_to(args.output).as_posix():hashlib.sha256(p.read_bytes()).hexdigest()
           for folder in ('models','textures') for p in sorted((args.output/folder).rglob('*')) if p.is_file()}
    (args.output/'award-models.json').write_text(json.dumps({'version':1,'models':results,'files':files},indent=2)+'\n')
    print(f'Cooked {len(results)} original ceremony models',flush=True)

if __name__=='__main__':main()
