#!/usr/bin/env python3
"""Cook original Scene/Model driver-selection and background models.

Uses the existing BRRES/GMDL/DSKM pipeline, retaining authored sel_wait/sel_gut
matrix animation and source receipts. Retail placement data and icon transforms
are exported separately; unsupported lighting remains explicit in receipts.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import struct
import subprocess
from concurrent.futures import ThreadPoolExecutor

from cook_model import cook

ROOT = Path(__file__).resolve().parents[1]
# MenuState character storage order, independent of each retail button position.
DRIVERS = ['mr', 'lg', 'pc_menu', 'ys', 'bmr', 'bpc', 'ko', 'nk', 'wr', 'wl',
           'dk', 'kp', 'bds', 'blg', 'ca', 'ds_menu', 'dd', 'ka', 'bk', 'fk',
           'kt', 'rs_menu', 'kk', 'jr']
BACKGROUNDS = ['trophy_kinoko', 'stop_watch', 'flag', 'baloon']
IDS = [0,7,16,10,6,1,8,14,11,2,9,3,4,12,17,15,18,5,21,22,19,23,13,20]
WEIGHTS = [1,1,1,1,0,0,0,0,2,2,2,2,0,0,1,1,1,0,2,2,2,2,0,1]
CHOICE_IDS = [0,1,2,6,7,8,3,4,5,9,10,11]
MACHINES = ['df_kart','a_kart','b_kart','df_bike','a_bike','b_bike',
            'c_kart','d_kart','e_kart','c_bike','d_bike','e_bike']

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def material_revision():
    return hashlib.sha256(b''.join((ROOT/'tools'/n).read_bytes() for n in
        ('export_brres.ts','retail_lighting.ts','cook_model.py','gx_material.py'))).hexdigest()

def extract_machines():
    from cook_roster import data_partition
    from extract_disc import Disc
    from unpack_szs import unpack
    inventory=json.loads((ROOT/'data/extracted/disc-files.json').read_text())
    files={f['name']:f for f in inventory['files']}
    partition=None
    for stem in DRIVERS:
        stem=stem.removesuffix('_menu')
        destination=ROOT/'assets/menu-models/Kart'/stem
        if (destination/'driver_anim.brres').is_file():continue
        name=f'Scene/Model/Kart/{stem}-allkart.szs'
        archive=ROOT/'data/extracted'/name
        if not archive.is_file():
            if partition is None:partition=data_partition(Disc(ROOT/inventory['identity']['source']))
            record=files[name];archive.parent.mkdir(parents=True,exist_ok=True)
            archive.write_bytes(partition.read(record['offset'],record['size']))
        unpack(archive,destination)

def machine_record(item, output, reuse_textures=False):
    i,choice=item
    stem=DRIVERS[i].removesuffix('_menu')
    source=ROOT/'assets/menu-models/Kart'/stem/f'{"sml"[WEIGHTS[i]]}{MACHINES[choice]}.brres'
    prefix=f'ui_machine_{i}_{choice}'
    receipt=output/'models'/f'{prefix}-source.json'
    if receipt.is_file():
        prior=json.loads(receipt.read_text())
        model=output/'models'/f'{prefix}_000.gmdl'
        if prior.get('conversion_revision')==3 and prior.get('material_converter_sha256')==material_revision() and prior['source_sha256']==sha(source) and model.is_file() and prior['model']['sha256']==sha(model):return prior
    export=ROOT/'build/menu-models'/prefix
    subprocess.run(['node',str(ROOT/'build/export_brres.mjs'),str(source),str(export),'menu'],
                   check=True,capture_output=True,text=True,env={**os.environ,'MKW_MENU_MATERIALS':'1'})
    parts=cook(export,output,prefix,max_texture=256,reuse_textures=reuse_textures)
    if len(parts)!=1:raise ValueError('Expected one bounded menu machine '+prefix)
    record={'key':f'machine_{i}_{choice}','prefix':prefix,'source':source.relative_to(ROOT).as_posix(),
            'source_sha256':sha(source),'model':parts[0],'conversion_revision':3,'material_converter_sha256':material_revision()}
    (output/'models'/f'{prefix}-source.json').write_text(json.dumps(record,indent=2)+'\n')
    return record

def write_seat_parameters():
    path=ROOT/'assets/menu-ui/MenuSingle/parameter/kartDriverDispParam.bin'
    data=path.read_bytes()
    # MenuDriverModel::GetPosition (USA 8084c768) adds this retail per-vehicle
    # seat height to the driver-specific Y delta. Raw delta alone drops bikers
    # below the chassis. Values from original REL at 808d5f38.
    base_y=[20,20,20,47,65,50,45,33,60,31,24,66,68,48,21,40,30,37,
            45,51,60,60,62,59,35,38,54,51,45,60,60,48,60,48,60,51]
    if struct.unpack_from('>2I',data)!=(36,48):raise ValueError('Unexpected source menu seat table')
    lines=['#pragma once','namespace mkw {',
           '// Original MenuSingle kartDriverDispParam.bin; generated by cook_menu_models.py.',
           'struct MenuSeat {float y,z;};','inline constexpr MenuSeat MenuSeats[24][12]={']
    for i in range(24):
        seats=[]
        for v in CHOICE_IDS:
            vehicle=v*3+WEIGHTS[i]
            y,z=struct.unpack_from('>2f',data,8+(vehicle*48+IDS[i])*56)
            seats.append((y+base_y[vehicle],z))
        lines.append(' {'+','.join('{%.9ff,%.9ff}'%s for s in seats)+'},')
    lines+=['};','}','']
    (ROOT/'include/mkw/menu_model_params.hpp').write_text('\n'.join(lines))

def write_icon_parameters():
    lines=['#pragma once','#include <cstdint>','namespace mkw {',
           '// MenuKartModel::Init 8084ef18; original IconParam records = retailVehicle/3.',
           'struct MenuIconParam { float scale, rx,ry,rz,x,y,z; };',
           'struct MenuIconTable { unsigned width,height,weight; MenuIconParam vehicles[12]; };',
           'inline constexpr MenuIconTable MenuIconTables[]={']
    sources=[]
    for path in sorted((ROOT/'assets/menu-ui/MenuSingle/parameter').glob('IconParam_*.bin')):
        _,width,height,weight=path.stem.split('_')
        data=path.read_bytes()
        if len(data)!=12*28:raise ValueError('Unexpected icon parameter length: '+str(path))
        values=[struct.unpack_from('>7f',data,i*28) for i in range(12)]
        lines+=[' {%s,%s,%d,{'%(width,height,'SML'.index(weight))+
                ','.join('{'+','.join('%.9ff'%v for v in row)+'}' for row in values)+'}},']
        sources.append({'source':path.relative_to(ROOT).as_posix(),'sha256':sha(path),
                        'width':int(width),'height':int(height),'weight':'SML'.index(weight),'vehicles':values})
    lines+=['};',
            'inline constexpr const MenuIconParam* menuIconParam(unsigned width,unsigned height,unsigned weight,unsigned retailVehicle){',
            ' for(const auto& table:MenuIconTables)if(table.width==width&&table.height==height&&table.weight==weight&&retailVehicle<36)return &table.vehicles[retailVehicle/3];',
            ' return nullptr;','}','}']
    (ROOT/'include/mkw/menu_icon_params.hpp').write_text('\n'.join(lines)+'\n')
    (ROOT/'build/menu-retail-audit').mkdir(parents=True,exist_ok=True)
    (ROOT/'build/menu-retail-audit/icon-parameters.json').write_text(json.dumps(sources,indent=2)+'\n')

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT/'sd-card/3ds/mkw-3ds')
    parser.add_argument('--only', nargs='+', help='Optional driver indices or background stems')
    parser.add_argument('--machines', action='store_true', help='Extract/cook all 288 original machine previews and seated CHR0 clips')
    parser.add_argument('--jobs',type=int,default=4)
    parser.add_argument('--reuse-textures',action='store_true',help='Verify/reuse unchanged texture files while recooking material/geometry data')
    args = parser.parse_args()
    receipt_path=args.output/'models/menu-models.json'
    records = json.loads(receipt_path.read_text())['models'] if receipt_path.is_file() else []
    records=[json.loads((args.output/'models'/f'{r["prefix"]}-source.json').read_text()) for r in records]
    if args.machines:
        extract_machines()
        write_seat_parameters()
        write_icon_parameters()
    sources = [(str(i), ROOT/'assets/menu-models/Driver'/f'{stem}.brres',
                f'ui_driver_{i}', 'sel_wait') for i, stem in enumerate(DRIVERS)]
    sources += [(stem, ROOT/'assets/menu-models/BackModel'/f'{stem}.brres',
                 f'ui_back_{i}', 'loop') for i, stem in enumerate(BACKGROUNDS)]
    for key, source, prefix, idle in sources:
        if args.only and key not in args.only:
            continue
        export = ROOT/'build/menu-models'/prefix
        result = subprocess.run(['node', str(ROOT/'build/export_brres.mjs'), str(source),
                                 str(export), 'model', idle, '0'],
                                check=True, capture_output=True, text=True,env={**os.environ,'MKW_MENU_MATERIALS':'1'})
        parts = cook(export, args.output, prefix, max_texture=256, preserve_vertices=True,reuse_textures=args.reuse_textures)
        if len(parts) != 1:
            raise ValueError('Menu animation needs one bounded model: '+prefix)
        animation_path = args.output/'models'/f'{prefix}.dskm'
        env=os.environ.copy()
        extra=ROOT/'assets/menu-models/Kart'/DRIVERS[int(key)].removesuffix('_menu')/'driver_anim.brres' if key.isdecimal() else None
        if extra and extra.is_file():env['MKW_ANIMATION_SOURCE']=str(extra)
        result = subprocess.run(['node', str(ROOT/'build/export_driver.mjs'), str(source),
                                 str(animation_path), 'model'],
                                check=True, capture_output=True, text=True,env=env)
        animation = json.loads(result.stdout)
        if animation['vertices'] != parts[0]['vertices']:
            raise ValueError('Menu animation/model vertex order mismatch: '+prefix)
        record = {'key': key, 'prefix': prefix, 'source': source.relative_to(ROOT).as_posix(),
                  'source_sha256': sha(source), 'animation_sha256': sha(animation_path),
                  'animation': animation, 'model': parts[0], 'idle_clip': idle,'conversion_revision':3,'material_converter_sha256':material_revision()}
        if extra and extra.is_file():record['seated_animation_source']={'path':extra.relative_to(ROOT).as_posix(),'sha256':sha(extra)}
        records=[r for r in records if r['prefix']!=prefix]+[record]
        (args.output/'models'/f'{prefix}-source.json').write_text(json.dumps(record, indent=2)+'\n')
    if args.machines:
        items=[(i,c) for i in range(24) for c in range(12)]
        with ThreadPoolExecutor(max_workers=args.jobs) as pool:
            for record in pool.map(lambda item:machine_record(item,args.output,args.reuse_textures),items):
                records=[r for r in records if r['prefix']!=record['prefix']]+[record]
                print('Cooked '+record['prefix'],flush=True)
    receipt = {'models': records,
               'geometry': 'Original menu BRRES with authored CHR0/PAT0/VIS0 matrix samples at 60 Hz',
               'limitations': ['Background framing remains a reference fit; driver/vehicle camera and transforms are recovered.',
                               'Existing compact material pipeline does not reproduce every GX TEV/reflection/light equation.',
                               'Mii identity models need profile customization and are not replaced with an unrelated avatar.']}
    receipt_path.write_text(json.dumps(receipt, indent=2)+'\n')
    print(f'Cooked {len(records)} original menu models')

if __name__ == '__main__':
    main()
