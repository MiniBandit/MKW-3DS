#!/usr/bin/env python3
"""Turn the LAN-play handshake icon into the game's include/mkw/lan_handshake_icon.hpp.

The icon is Font Awesome Free 6's "handshake" (CC BY 4.0, credited in NOTICE and
licenses/fontawesome-free-icons.txt), kept as tools/art/handshake-fontawesome6.svg.
It is drawn white, so the header holds only its coverage (one byte per pixel).
Run by hand when the icon changes: needs rsvg-convert (librsvg) and Pillow.

    python3 tools/make_lan_icon.py
"""
import io,subprocess
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
SVG=ROOT/'tools/art/handshake-fontawesome6.svg';OUT=ROOT/'include/mkw/lan_handshake_icon.hpp'
W,H=160,128
svg=SVG.read_text().replace('<svg ','<svg fill="black" ',1)
png=subprocess.run(['rsvg-convert','-w',str(W),'-h',str(H),'--keep-aspect-ratio'],input=svg.encode(),capture_output=True,check=True).stdout
image=Image.open(io.BytesIO(png)).convert('RGBA')
canvas=Image.new('RGBA',(W,H));canvas.paste(image,((W-image.width)//2,(H-image.height)//2))
alpha=canvas.getchannel('A').tobytes()
rows=[', '.join(str(b) for b in alpha[i:i+32]) for i in range(0,len(alpha),32)]
OUT.write_text('#pragma once\n// Generated by tools/make_lan_icon.py from Font Awesome Free 6 "handshake"\n'
 '// (https://fontawesome.com, CC BY 4.0). Coverage per pixel, top row first.\n#include <cstdint>\n'
 f'namespace mkw {{\ninline constexpr unsigned LanHandshakeIconWidth={W},LanHandshakeIconHeight={H};\n'
 'inline constexpr uint8_t LanHandshakeIcon[]={\n'+',\n'.join(rows)+'\n};\n}\n')
print(OUT.relative_to(ROOT),len(alpha),'bytes')
