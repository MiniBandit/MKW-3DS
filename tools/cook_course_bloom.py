#!/usr/bin/env python3
"""Cook the authored EGG Bloom parameters, without inventing a gain formula.

USA DrawPathBloom::CalcImpl 8021c9a4 maps threshold through (16+219*t)/255,
uses blur1's strength/intensity, and derives blur2 stage2 intensity from
stage1/2. PostEffectBlur samples rings of 8 and 16 taps. Composite weights
are the two floats at 0x9c, not a multiplier for their summed intensities.
"""
import hashlib,json,math,struct
from pathlib import Path
from cook_course_lighting import archive
ROOT=Path(__file__).resolve().parents[1]

def parse(data):
    if len(data)!=0xa4 or data[:4]!=b'PBLM' or data[8]!=1:
        raise ValueError('Expected retail PBLM v1, 164 bytes')
    result={'threshold':struct.unpack_from('>f',data,0x10)[0],
        'thresholdColor':int.from_bytes(data[0x14:0x18],'big'),
        'tint':int.from_bytes(data[0x18:0x1c],'big'),
        'flags':struct.unpack_from('>H',data,0x1c)[0],
        'blur':[list(struct.unpack_from('>2f',data,0x20+i*0x20)) for i in range(3)],
        'output':data[0x80],'stages':data[0x81],
        'weights':list(struct.unpack_from('>2f',data,0x9c))}
    values=[result['threshold'],*result['weights'],*(v for pair in result['blur'] for v in pair)]
    if not all(math.isfinite(v) and v>=0 for v in values):raise ValueError('Invalid Bloom parameter')
    if result['flags'] not in (11,43) or result['output']!=1 or result['stages']!=2:
        raise ValueError('Untranslated retail Bloom variant')
    return result

def main():
    rows=[];evidence=[]
    for source in sorted((ROOT/'data/extracted/Race/Course').glob('*.szs')):
        if source.name.startswith('._'):continue
        files=archive(source);default=None
        for name,data in sorted(files.items()):
            if not name.endswith('.bblm'):continue
            params=parse(data);evidence.append({'archive':'Race/Course/'+source.name,'resource':name,
                'sha256':hashlib.sha256(data).hexdigest(),'parameters':params})
            if name.lstrip('./')=='posteffect/posteffect.bblm':default=params
        if default is None:raise ValueError('Missing default BBLM: '+str(source))
        rows.append(('Race/Course/'+source.name,default))
    if len(rows)!=42:raise ValueError('Expected all 42 original courses')
    f=lambda v:format(v,'.9g')+('.f' if float(v).is_integer() else 'f')
    lines=['// Generated by tools/cook_course_bloom.py from retail PBLM v1.',
        '#pragma once','#include <cstdint>','#include <cstring>','namespace mkw {',
        'struct CourseBloom {const char* archive;float threshold;uint32_t thresholdColor,tint;unsigned flags;',
        ' float strength[2],intensity[2],weight[2];',
        ' bool enabled()const{return weight[0]>0||weight[1]>0;}};',
        'inline constexpr CourseBloom CourseBlooms[]={']
    for name,p in rows:
        arrays=[p['blur'][0:2],p['weights']]
        lines.append('{'+','.join([json.dumps(name),f(p['threshold']),hex(p['thresholdColor'])+'u',hex(p['tint'])+'u',str(p['flags']),
            '{'+','.join(f(pair[0]) for pair in arrays[0])+'}',
            '{'+','.join(f(pair[1]) for pair in arrays[0])+'}',
            '{'+','.join(f(v) for v in arrays[1])+'}'])+'},')
    lines+=['};','inline const CourseBloom* courseBloom(const char* archive){',
        ' for(const auto& b:CourseBlooms)if(!std::strcmp(b.archive,archive))return &b;return nullptr;','}','}']
    (ROOT/'include/mkw/course_bloom.hpp').write_text('\n'.join(lines)+'\n')
    (ROOT/'build/course-bloom.json').write_text(json.dumps({'courses':len(rows),'sourceFiles':evidence,
        'adaptation':'Full 128x64 near and 64x32 far surfaces with authored screen-space radii; ring taps halve on reduced quality; gain stays unchanged.',
        'runtime_validation':'Dad manual, pending'},indent=2)+'\n')
    print(json.dumps({'courses':len(rows),'source_files':len(evidence)}))
if __name__=='__main__':main()
