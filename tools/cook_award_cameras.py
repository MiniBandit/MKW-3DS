"""Generate compact original SCN0 camera keys; no frame baking or replacement paths."""
import json
from pathlib import Path
from cook_race_flow import f
CHANNELS=('posX','posY','posZ','aspect','near','far','rotX','rotY','rotZ','aimX','aimY','aimZ','twist','perspFovy','orthoHeight')

def cook_award_cameras(source, target):
    archives=json.loads(source.read_text())['archives']
    header=['// Generated by tools/cook_award_cameras.py from original ceremony SCN0.',
            '#pragma once','#include <mkw/award_camera.hpp>','namespace mkw {']
    clips=[]
    for resource,archive in archives.items():
        for scene in archive['scenes']:
            for camera in scene['cameras']:
                tracks=[]
                for channel in CHANNELS:
                    track=camera[channel]
                    if track['type'] not in (0,1):raise ValueError('Unsupported SCN0 track type')
                    keys=track['frames']
                    name=f'AwardCameraKeys{len(clips)}_{channel}'
                    header.append(f'inline constexpr AwardCameraKey {name}[]={{')
                    for i,key in enumerate(keys):
                        values=(key['frame'],key['value'],key['tangent']) if track['type']==1 else (i,key,0)
                        header.append('{'+','.join(f(x) for x in values)+'},')
                    header.append('};')
                    tracks.append('{'+f'{name},{len(keys)},{str(track["type"]==1).lower()}'+'}')
                clips.append('{'+json.dumps(scene['name'])+','+f(scene['duration'])+','+
                             str(scene['loopMode']==1).lower()+f',{camera["cameraType"]},{camera["projType"]},'+
                             '{{'+','.join(tracks)+'}}}')
    header.append('inline constexpr AwardCameraClip AwardCameraClips[]={'+','.join(clips)+'};')
    header.append('}')
    target.write_text('\n'.join(header)+'\n')
    print(f'Cooked {len(clips)} original ceremony camera clips')

if __name__=='__main__':
    root=Path(__file__).resolve().parents[1]
    cook_award_cameras(root/'build/award-source/scene-bindings.json',root/'include/mkw/award_camera_data.hpp')
