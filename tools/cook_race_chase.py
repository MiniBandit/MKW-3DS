#!/usr/bin/env python3
"""Cook CtrlRaceItemBalloon assets: Race/game_image chase_icon (the incoming-item
warning icon) from the locally extracted Race archive.

Geometry, materials and animation keys come from chase_icon.brctr (variant
chase_icon_1), chase_icon.brlyt and its five BRLANs; the item pictures are the
item.brlyt panes CtrlRaceItemBalloon names (fn_1_35073C, PAL 0x80860AF0), which
use the same TPLs as the item window's HudItems icons. Textures go to
build/vfx/textures (overlaid by tools/package_sd.py); the generated header is
include/mkw/race_chase_layout.hpp.
"""
import struct
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
sys.path.insert(0, str(ROOT / 'vendor/gclib'))
from cook_race_flow import parse_layout, controller_clips, controller_variants, texture_file, f, rgba, string
from cook_race_items import decode_tpl, ICONS

UI = ROOT / 'assets/race-ui/Race/game_image'
# CtrlRaceItemBalloon's pictures: item.brlyt pane -> the picture CtrlRaceItemBalloon
# asks fn_1_35073C for (item id, as the item window numbers them).
PICTURES = {'kame_red': 1, 'kame_wing': 7, 'star': 9, 'kinoko_big': 11, 'thunder_c': 14, 'killer': 15}


def reversed_clips(control):
    """BRCTR animation records: name -> the reverse-playback flag (u16 at +6)."""
    d = control.read_bytes()
    offset, _, strings = struct.unpack_from('>3H', d, 12)
    count, _, anims = struct.unpack_from('>3H', d, offset + 2)
    table = offset + 8 + count * 8
    return {string(d, strings + struct.unpack_from('>H', d, table + j * 12)[0]): struct.unpack_from('>H', d, table + j * 12 + 6)[0] != 0
            for j in range(anims)}


def main():
    out = ROOT / 'build/vfx'
    (out / 'textures').mkdir(parents=True, exist_ok=True)
    layout = parse_layout(UI / 'blyt/chase_icon.brlyt')
    panes = {p['name']: p for p in layout['panes']}
    if [p['name'] for p in layout['panes']] != ['RootPane', 'chase_icon_null', 'base', 'hilight', 'item']:
        raise ValueError('Unexpected chase_icon panes')
    if any(panes[n]['parent'] != 1 or panes[n]['origin'] != 4 for n in ('base', 'hilight', 'item')):
        raise ValueError('chase_icon pictures are expected centred under chase_icon_null')
    clips = controller_clips(UI / 'ctrl/chase_icon.brctr', layout, UI / 'anim')
    reverse = reversed_clips(UI / 'ctrl/chase_icon.brctr')
    variant = controller_variants(UI / 'ctrl/chase_icon.brctr')['chase_icon_1']
    # item.brlyt pictures share the item window's TPLs (tools/cook_race_items.py ICONS).
    item = parse_layout(UI / 'blyt/item.brlyt')
    for name, ident in PICTURES.items():
        pane = next(p for p in item['panes'] if p['name'] == name)
        if item['materials'][pane['material']]['texture'] != ICONS[ident] + '.tpl':
            raise ValueError(f'item.brlyt {name} is not HudItems {ident}')
    textures = [texture_file(decode_tpl(UI / 'timg/tt_chase_icon.tpl'), 'hud_chase_icon', out, 'rgba8'),
                texture_file(decode_tpl(UI / 'timg/tt_chase_icon_light.tpl'), 'hud_chase_icon_light', out, 'la4')]
    slot = {'tt_chase_icon.tpl': 0, 'tt_chase_icon_light.tpl': 1}

    lines = ['#pragma once', '#include <array>', '#include <cstdint>', '#include <mkw/race_flow_layout.hpp>', 'namespace mkw {',
             '// Generated by tools/cook_race_chase.py from game_image chase_icon.brctr (chase_icon_1),',
             '// chase_icon.brlyt, its BRLANs and item.brlyt (CtrlRaceItemBalloon, PAL load 0x807F1F50).',
             f'inline constexpr std::array<const char*,2> ChaseTextures{{{{"{textures[0]}","{textures[1]}"}}}};',
             '// chase_icon_1 16:9 control transform: x, y (layout units, y up), scale x, y.',
             f'inline constexpr float ChaseControl[4]={{{f(variant["x"])},{f(variant["y"])},{f(variant["sx"])},{f(variant["sy"])}}};',
             '// Pictures under chase_icon_null, in draw order: size x authored scale (layout units),',
             '// NW4R material lerp(C0, C1, texture) as RRGGBBAA, texture (ChaseTextures; -1: the picture).',
             'struct ChasePicture {float w,h;uint32_t color0,color1;int8_t texture;};']
    for name in ('base', 'hilight', 'item'):
        p, m = panes[name], layout['materials'][panes[name]['material']]
        v = p['values']
        if p['vertex'] != [[255] * 4] * 4 or p['uv'] != [0, 0, 1, 0, 0, 1, 1, 1] or m['srt'] != [0, 0, 0, 1, 1] or m['wrap'] != (0, 0):
            raise ValueError(f'chase_icon {name}: unexpected vertex colours, UVs or sampler')
        texture = -1 if name == 'item' else slot[m['texture']]
        lines.append(f'inline constexpr ChasePicture Chase{name.capitalize()}{{{f(v[8] * v[6])},{f(v[9] * v[7])},'
                     f'0x{rgba(m["c0"]):08x}u,0x{rgba(m["c1"]):08x}u,{texture}}};')
    lines += ['// BRCTR clips (UIAnimator group, clip): frames, loop, next clip (-1: hold), reverse',
              '// playback, and their one track: eFade chase_icon_null alpha, roop hilight rotation Z,',
              '// zoom item scale (X and Y share keys).',
              'struct ChaseClip {float frames;bool loop;int8_t next;bool reverse;uint16_t first,count;};']
    keys = []
    def emit(name, group, members, track):
        rows = []
        for c in members:
            tracks = [t for t in c['tracks'] if (t['kind'], t['index']) == track]
            if len(tracks) != 1 or tracks[0]['step'] or len(c['tracks']) != len(tracks) * (2 if track == (0, 6) else 1):
                raise ValueError(f'chase_icon {c["name"]}: unexpected tracks')
            if track == (0, 6) and any(t['keys'] != tracks[0]['keys'] for t in c['tracks']):
                raise ValueError('chase_icon zoom: item X and Y scale keys differ')
            nxt = [m['name'] for m in members].index(c['next']) if c['next'] else -1
            rows.append(f'{{{f(c["frames"])},{str(c["loop"]).lower()},{nxt},{str(reverse[c["name"]]).lower()},{len(keys)},{len(tracks[0]["keys"])}}}')
            keys.extend(tracks[0]['keys'])
            if c['rate'] != 1:
                raise ValueError(f'chase_icon {c["name"]}: BRCTR rate {c["rate"]}')
        lines.append(f'inline constexpr ChaseClip {name}[{len(rows)}]{{{",".join(rows)}}}; // {", ".join(c["name"] + " " + c["source"].name for c in members)}')
    groups = {g: [c for c in clips if c['group'] == g] for g in ('eFade', 'roop', 'zoom')}
    if [c['name'] for c in groups['eFade']] != ['alpha_0', 'fade_in', 'alpha_255', 'fade_out']:
        raise ValueError('Unexpected eFade clips')
    emit('ChaseFade', 'eFade', groups['eFade'], (1, 16))
    emit('ChaseRoop', 'roop', groups['roop'], (0, 5))
    emit('ChaseZoom', 'zoom', groups['zoom'], (0, 6))
    lines.append('inline constexpr FlowKey ChaseKeys[]={')
    lines += ['    ' + ','.join(f'{{{f(k[0])},{f(k[1])},{f(k[2])}}}' for k in keys[i:i + 4]) + ',' for i in range(0, len(keys), 4)]
    lines += ['};', '// fn_1_35073C pictures (item.brlyt panes, the same TPLs as HudItems): HudItems index.']
    lines += [f'inline constexpr uint8_t ChasePicture{label}={PICTURES[name]}; // {name}'
              for label, name in (('Red', 'kame_red'), ('Blue', 'kame_wing'), ('Star', 'star'), ('Mega', 'kinoko_big'),
                                  ('Cloud', 'thunder_c'), ('Bullet', 'killer'))]
    lines += ['}', '']
    (ROOT / 'include/mkw/race_chase_layout.hpp').write_text('\n'.join(lines))
    print('Cooked chase icon:', ', '.join(textures))


if __name__ == '__main__':
    main()
