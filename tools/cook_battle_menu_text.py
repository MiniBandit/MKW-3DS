#!/usr/bin/env python3
"""Stage new battle-rule captions from the original BRFNT, preserving the base UI."""
import argparse,hashlib,json
from pathlib import Path
from cook_race_hud import font_strings
from cook_race_items import cook_image_sprite
from cook_roster import ROOT

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,default=ROOT/'build/battle-menu-assets')
    args=parser.parse_args();out=args.output;out.mkdir(parents=True,exist_ok=True)
    labels=['Wins','Stages']+['Wins: '+str(n) for n in (2,3,4,5,8,10)]
    source=ROOT/'assets/race-ui/Font/kart_kanji_font.brfnt'
    sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
    before=sha(source);glyphs=font_strings(source,labels);rows=[];records=[]
    for i,label in enumerate(labels):
        r=cook_image_sprite(glyphs[label],'battle_rule_text_'+str(i),out)
        gpu=r['padded'][0]*r['padded'][1]*4
        rows.append('{'+','.join((json.dumps(r['name']),json.dumps(r['path']),f"{r['width']}.f",f"{r['height']}.f",f"{r['u']:.9f}f",f"{r['v']:.9f}f",json.dumps(label),'0','0',str(gpu)))+'},')
        p=out/r['path'];records.append({'path':r['path'],'bytes':p.stat().st_size,'sha256':sha(p),'text':label})
    assert sha(source)==before
    (ROOT/'include/mkw/battle_menu_text.inc').write_text('// Generated by cook_battle_menu_text.py; original BRFNT.\n'+'\n'.join(rows)+'\n')
    (out/'receipt.json').write_text(json.dumps({'source':str(source.relative_to(ROOT)),'source_sha256':before,'files':records},indent=2)+'\n')
    print('Staged',len(records),'battle captions:',out)
if __name__=='__main__':main()
