#!/usr/bin/env python3
"""Cook CtrlRaceNameBalloon assets: retail character names, line and layout.

Names: Common.bmg 0x2328 + character id (USA 0x8081b874), drawn with the
layout's kart_kanji_font. Geometry: Race/game_image chara_name.brlyt with the
balloon.brctr balloon_1_0 variant. Output stays in build/vfx (overlaid by
tools/resource_manifest.py); the generated header is include/mkw/race_balloon.hpp.
"""
import struct, subprocess, sys
from pathlib import Path
from PIL import Image
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
sys.path.insert(0, str(ROOT / 'vendor/gclib'))
from cook_race_hud import font_strings, layout, sections, variant
from cook_race_items import decode_tpl
from menu_layout import messages
from devkitpro import tool


def font_metrics(path):
    data = path.read_bytes()
    for tag, _, start in sections(data):
        if tag == b'FINF':
            height, width, ascent = data[start + 20], data[start + 21], data[start + 22]
            return height, width
    raise ValueError('BRFNT without FINF')


def texture(image, name, output, fmt):
    w, h = image.size
    padded = Image.new('RGBA', tuple(max(8, 1 << (v - 1).bit_length()) for v in image.size))
    padded.paste(image, (0, 0))
    png = output / 'textures' / (name + '.png')
    png.parent.mkdir(parents=True, exist_ok=True)
    padded.save(png)
    subprocess.run([str(tool('tex3ds')), '-f', fmt, '-z', 'none', '-o', str(png.with_suffix('.t3x')), str(png)],
                   check=True, stdout=subprocess.DEVNULL)
    return w, h, w / padded.size[0], h / padded.size[1]


def main():
    output = ROOT / 'build/vfx'
    ui = ROOT / 'assets/race-ui/Race/game_image'
    font = ROOT / 'assets/race-ui/Font/kart_kanji_font.brfnt'
    common = messages(ROOT / 'assets/race-ui/Race_U/message/Common.bmg')
    names = [common[0x2328 + i] for i in range(24)] + ["Mii"]
    images = font_strings(font, names)
    font_height, font_width = font_metrics(font)
    records = []
    for i, name in enumerate(names):
        w, h, u, v = texture(images[name], f'hud_name_{i:02d}', output, 'la4')
        records.append((f'textures/hud_name_{i:02d}.t3x', w, h, u, v, name))
    lw, lh, lu, lv = texture(decode_tpl(ui / 'timg/tt_race_chara_name_line_white_ver00.tpl'), 'hud_balloon_line', output, 'rgba8')
    panes = layout(ui / 'blyt/chara_name.brlyt')
    data = (ui / 'blyt/chara_name.brlyt').read_bytes()
    font_size = None
    for tag, _, start in sections(data):
        if tag == b'txt1' and data[start + 4:start + 0x14].split(b'\0')[0] == b'chara_name':
            p = start + 0x44
            position = data[p + 8]
            font_size = struct.unpack_from('>2f', data, p + 24)
    if not font_size:
        raise ValueError('chara_name text pane missing')
    _, _, _, sx, sy = variant(ui / 'ctrl/balloon.brctr', 'balloon_1_0')
    line, text = panes['line'], panes['chara_name']
    lines = ['#pragma once', '#include <array>', 'namespace mkw {',
             '// Generated by tools/cook_race_balloon.py from chara_name.brlyt, balloon.brctr',
             '// (balloon_1_0) and Common.bmg character names (0x2328 + Kinoko character id).',
             'struct BalloonName { const char* path; float width,height,u,v; };',
             'inline constexpr std::array<BalloonName,25> BalloonNames{{']
    lines += [f'    {{"{p}",{w}.f,{h}.f,{u:.6f}f,{v:.6f}f}}, // {n}' for p, w, h, u, v, n in records]
    lines += ['}};',
              f'inline constexpr const char* BalloonLinePath="textures/hud_balloon_line.t3x";',
              f'inline constexpr float BalloonLineUV[2]={{{lu:.6f}f,{lv:.6f}f}};',
              '// Layout units (y up) relative to chara_name_null, already in the variant scale.',
              f'inline constexpr float BalloonLine[4]={{{line["x"] * sx:.4f}f,{line["y"] * sy:.4f}f,{line["w"] * line["sx"] * sx:.4f}f,{line["h"] * line["sy"] * sy:.4f}f}};',
              f'inline constexpr float BalloonText[4]={{{text["x"] * sx:.4f}f,{text["y"] * sy:.4f}f,{text["w"] * text["sx"] * sx:.4f}f,{text["h"] * text["sy"] * sy:.4f}f}};',
              f'inline constexpr unsigned BalloonTextPosition={position}; // H = %3 (2 right), V = /3 (1 centre)',
              f'inline constexpr float BalloonFontScale[2]={{{font_size[0] * sx / font_width:.6f}f,{font_size[1] * sy / font_height:.6f}f}}; // fontSize / BRFNT width,height',
              '}', '']
    (ROOT / 'include/mkw/race_balloon.hpp').write_text('\n'.join(lines))
    print(f'Cooked {len(records)} balloon names; font {font_width}x{font_height}, size {font_size}, text position {position}')


if __name__ == '__main__':
    main()
