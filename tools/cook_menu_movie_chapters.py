"""Preserve the retail cup movie chapter markers from its unused bottom strip."""
from pathlib import Path
from menu_movies import ThpMovie
from cook_roster import ROOT

def cook():
    movie = ThpMovie(ROOT/'data/extracted/thp/course/cup_select.thp')
    chapters = []
    # MoviePlayer update (USA805dc494): choose the brightest of five Y
    # samples at (8 + 16*i, height - 8). First maximum wins ties.
    for frame in range(movie.count):
        image = movie.frame(frame).convert('L')
        values = [image.getpixel((8 + 16*i, image.height-8)) for i in range(5)]
        chapters.append(values.index(max(values)))
    text = '#pragma once\nnamespace mkw {\n// Generated by tools/cook_menu_movie_chapters.py.\n'
    text += 'inline constexpr unsigned char CupMovieChapters[]={' + ','.join(map(str,chapters)) + '};\n}\n'
    (ROOT/'include/mkw/menu_movie_chapters.hpp').write_text(text)
    print('Cup movie chapters:', len(chapters), 'frames')

if __name__ == '__main__': cook()
