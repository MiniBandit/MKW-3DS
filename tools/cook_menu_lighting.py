#!/usr/bin/env python3
"""Preserve MenuSingle's original EGG light and light-texture parameters."""
import hashlib
import json
from pathlib import Path
from cook_course_lighting import ROOT, LIGHTS, RETAIL_TEXTURE_LIGHTS, parse_blight, parse_blmap, header


def main():
    parameter = ROOT / 'assets/menu-ui/MenuSingle/parameter'
    light, light_map = parameter / 'default.blight', parameter / 'default.blmap'
    result = parse_blight(light.read_bytes())
    result['textures'] = parse_blmap(light_map.read_bytes())['textures']
    result['fog'] = []
    if len(result['lights']) != LIGHTS or len(result['ambients']) != LIGHTS:
        raise ValueError('Unexpected menu light/ambient count')
    if any(l['type'] != 1 for l in result['lights'] if l['flags'] & 1):
        raise ValueError('Menu uses a non-directional light')
    if [t['name'] for t in result['textures']] != ['lm_0', 'lm_1']:
        raise ValueError('Unexpected menu light textures')
    if any(t['type'] != 0 or len(t['entries']) > RETAIL_TEXTURE_LIGHTS for t in result['textures']):
        raise ValueError('Unsupported menu light texture')
    source = header([('Scene/UI/MenuSingle', result)])
    source = source.replace('CourseLightings', 'MenuLightings').replace('courseLighting(', 'menuLighting(')
    source = source.replace('// Generated by tools/cook_course_lighting.py from posteffect .blight/.blmap/.bfg\n// (Common lightset/default.* when a course has none).',
                            '// Generated by tools/cook_menu_lighting.py from MenuSingle/parameter/default.blight/.blmap.')
    (ROOT / 'include/mkw/menu_lighting.hpp').write_text(source)
    result['sources'] = {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in (light, light_map)}
    (ROOT / 'build/menu-lighting.json').write_text(json.dumps(result, indent=2) + '\n')
    print('Preserved 16 menu lights and original lm_0/lm_1 parameters')


if __name__ == '__main__':
    main()
