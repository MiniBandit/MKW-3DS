#!/usr/bin/env python3
"""Extract and cook the retail drivers from a user-supplied retail disc.

The default, full-detail single-player Standard Kart archives are used. Regional
disc contents and every decrypted sector are verified by extract_disc.py. No
game content is downloaded. Each character has an independent output prefix so
only the selected character's geometry and textures need be resident on 3DS.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import sys

from extract_disc import Disc, Partition
from unpack_szs import unpack

ROOT = Path(__file__).resolve().parents[1]
# IDs are the original game IDs in Kinoko's include/Common.hh. Archive stems
# come from the disc's FST. The order starts with Mario, then each weight class.
ROSTER = [
    ("mario", "Mario", 0, "mr", "m"),
    ("luigi", "Luigi", 7, "lg", "m"),
    ("peach", "Peach", 16, "pc", "m"),
    ("yoshi", "Yoshi", 10, "ys", "m"),
    ("baby_mario", "Baby Mario", 6, "bmr", "s"),
    ("baby_peach", "Baby Peach", 1, "bpc", "s"),
    ("toad", "Toad", 8, "ko", "s"),
    ("koopa_troopa", "Koopa Troopa", 14, "nk", "s"),
    ("wario", "Wario", 11, "wr", "l"),
    ("waluigi", "Waluigi", 2, "wl", "l"),
    ("donkey_kong", "Donkey Kong", 9, "dk", "l"),
    ("bowser", "Bowser", 3, "kp", "l"),
    ("baby_daisy", "Baby Daisy", 4, "bds", "s"),
    ("baby_luigi", "Baby Luigi", 12, "blg", "s"),
    ("birdo", "Birdo", 17, "ca", "m"),
    ("daisy", "Daisy", 15, "ds", "m"),
    ("diddy_kong", "Diddy Kong", 18, "dd", "m"),
    ("dry_bones", "Dry Bones", 5, "ka", "s"),
    ("dry_bowser", "Dry Bowser", 21, "bk", "l"),
    ("funky_kong", "Funky Kong", 22, "fk", "l"),
    ("king_boo", "King Boo", 19, "kt", "l"),
    ("rosalina", "Rosalina", 23, "rs", "l"),
    ("toadette", "Toadette", 13, "kk", "s"),
    ("bowser_jr", "Bowser Jr.", 20, "jr", "m"),
]


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def seat_offset(display, vehicle_id, character_id):
    offset = 8 + (vehicle_id * 48 + character_id) * 56
    y, z = struct.unpack_from(">2f", display, offset)
    return [0.0, y, z]


def write_native_roster(display):
    header = ROOT / "include/mkw/roster.hpp"
    lines = ["#pragma once", "#include <array>", "namespace mkw {",
             "// Generated by tools/cook_roster.py from retail IDs and display parameters.",
             "struct DriverChoice {const char* name;const char* prefix;unsigned character,vehicle;float seatY,seatZ;};",
             f"inline constexpr std::array<DriverChoice,{len(ROSTER)}> StarterDrivers{{{{"]
    for slug, name, character_id, _, size in ROSTER:
        vehicle_id = {"s": 0, "m": 1, "l": 2}[size]
        _, y, z = seat_offset(display, vehicle_id, character_id)
        lines.append(f'    {{{json.dumps(name)},"{slug}_",{character_id},{vehicle_id},{y:.9f}f,{z:.9f}f}},')
    lines.extend(["}};", "}", ""])
    header.write_text("\n".join(lines))


def data_partition(disc):
    candidates = []
    for group in range(4):
        count, table = struct.unpack(">II", disc.read(0x40000 + group * 8, 8))
        if count > 32:
            raise ValueError("Invalid partition count")
        for index in range(count):
            offset, kind = struct.unpack(">II", disc.read(table * 4 + index * 8, 8))
            if kind == 0:
                candidates.append(offset * 4)
    if len(candidates) != 1:
        raise ValueError("Expected one retail data partition")
    return Partition(disc, candidates[0])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("disc", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--characters", nargs="+", choices=[r[0] for r in ROSTER])
    parser.add_argument("--extract-only", action="store_true")
    parser.add_argument("--skip-animations", action="store_true")
    args = parser.parse_args()
    extracted = ROOT / "data/extracted"
    # Refresh offsets from this exact disc; do not trust a stale FST receipt.
    subprocess.run([sys.executable, str(ROOT / "tools/extract_disc.py"),
                    str(args.disc), str(extracted), "--list-only"], check=True)
    inventory = json.loads((extracted / "disc-files.json").read_text())
    files = {entry["name"]: entry for entry in inventory["files"]}
    disc = Disc(args.disc)
    partition = data_partition(disc)
    audit = {"identity": inventory["identity"], "sector_h0_verified": True,
             "source_ids": "vendor/kinoko/include/Common.hh", "characters": []}
    common_name = "Race/Common.szs"
    common_entry = files[common_name]
    common_archive = extracted / common_name
    common_archive.parent.mkdir(parents=True, exist_ok=True)
    common_archive.write_bytes(partition.read(common_entry["offset"], common_entry["size"]))
    unpack(common_archive, ROOT / "assets/common")
    display_path = ROOT / "assets/common/kartDriverDispParam.bin"
    display = display_path.read_bytes()
    vehicle_count, character_count = struct.unpack_from(">II", display)
    if (vehicle_count, character_count) != (36, 48) or len(display) != 8 + 36 * 48 * 56:
        raise ValueError("Unexpected original kart/driver display parameter layout")
    audit["seat_offset_source"] = display_path.relative_to(ROOT).as_posix()
    audit["seat_offset_source_sha256"] = sha256(display_path)
    write_native_roster(display)
    destination = ROOT / "assets/roster"
    destination.mkdir(parents=True, exist_ok=True)
    for slug, name, character_id, code, size in ROSTER:
        if args.characters and slug not in args.characters:
            continue
        archive_name = f"Race/Kart/{size}df_kart-{code}.szs"
        entry = files[archive_name]
        archive_path = extracted / archive_name
        archive_path.parent.mkdir(parents=True, exist_ok=True)
        archive_path.write_bytes(partition.read(entry["offset"], entry["size"]))
        archive = destination / slug
        unpack(archive_path, archive)
        inspection = archive / "inspection"
        result = subprocess.run([
            "node", str(ROOT / "build/export_brres.mjs"),
            str(archive / "driver_model.brres"), str(inspection),
            "model", "drive", "15"], check=True, capture_output=True, text=True)
        geometry = json.loads(result.stdout)
        (inspection / "nodes.json").write_text(json.dumps(geometry["nodes"], indent=2) + "\n")
        record = {
            "slug": slug, "name": name, "character_id": character_id,
            "vehicle_id": {"s": 0, "m": 1, "l": 2}[size],
            "prefix": slug + "_", "archive": archive_name,
            "archive_sha256": sha256(archive_path),
            "driver_sha256": sha256(archive / "driver_model.brres"),
            "kart_sha256": sha256(archive / "kart_model.brres"),
            "clips": json.loads((inspection / "animations.json").read_text()),
            "nodes": geometry["nodes"],
        }
        record["seatOffset"] = seat_offset(display, record["vehicle_id"], character_id)
        audit["characters"].append(record)
        if not args.extract_only:
            subprocess.run([sys.executable, str(ROOT / "tools/cook_vehicle.py"),
                            str(archive), str(args.output), "--prefix", slug + "_"], check=True)
            if not args.skip_animations:
                subprocess.run([sys.executable, str(ROOT / "tools/cook_animations.py"),
                                str(archive), str(args.output / "models"),
                                "--prefix", slug + "_"], check=True)
        print(f"{name}: {len(record['clips'])} original driver clips", flush=True)
    disc.f.close()
    (destination / "roster-audit.json").write_text(json.dumps(audit, indent=2) + "\n")
    if not args.extract_only:
        models = args.output / "models"
        models.mkdir(parents=True, exist_ok=True)
        records = {row["slug"]: row for row in audit["characters"]}
        prior = models / "roster.json"
        if args.characters and prior.exists():
            for row in json.loads(prior.read_text())["characters"]:
                records.setdefault(row["slug"], row)
        manifest = {"version": 1, "characters": [
            {key: value for key, value in row.items() if key not in ("nodes",)}
            for slug, *_ in ROSTER if (row := records.get(slug))]}
        (models / "roster.json").write_text(json.dumps(manifest, indent=2) + "\n")


if __name__ == "__main__":
    main()
