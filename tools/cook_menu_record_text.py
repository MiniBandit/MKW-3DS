#!/usr/bin/env python3
"""Stage record captions with ordinary footer ink and the original race clock digits."""
from pathlib import Path
import argparse,hashlib,json
import numpy as np
from PIL import Image
from cook_roster import ROOT
from cook_race_hud import font_strings
from cook_race_items import cook_image_sprite,decode_tpl
from cook_menu_ui import font_style
from cook_menu_footer import footer_ink

def cook(output=None):
 out=output or ROOT/'build/menu-record-assets';out.mkdir(parents=True,exist_ok=True)
 font=ROOT/'assets/race-ui/Font/kart_kanji_font.brfnt'
 labels=[(f'class_{i}',f'{cc} Trophy: ')for i,cc in enumerate(['50cc','100cc','150cc','Mirror'])]+[('rank',' Rank: '),('none','--'),('best','Best Time')]
 raw=font_strings(font,[t for _,t in labels]+['-']);footer_raw=font_strings(font,[t for k,t in labels if k!='best'],full_ink=True);rows=[];files=[];sources={}
 sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
 def source(p):sources[str(p.relative_to(ROOT))]=sha(p)
 source(font)
 def add(image,key,text='',style=0):
  r=cook_image_sprite(image,'ui_menu_record_'+key,out);p=out/r['path']
  files.append({'path':r['path'],'bytes':p.stat().st_size,'sha256':sha(p)})
  rows.append('{'+','.join([json.dumps('menu_record_'+key),json.dumps(r['path']),f"{r['width']}.f",f"{r['height']}.f",f"{r['u']:.9f}f",f"{r['v']:.9f}f",json.dumps(text),'0',str(style),str(r['padded'][0]*r['padded'][1]*4)])+'},')
  assert image.getchannel('A').getextrema()[0]==0,key
 for key,text in labels:
  # Original MenuObiInstructionText/footer_help style33; Best uses white style8.
  colors=[[47,35,71,0],[255,255,255,255]] if key!='best' else [[0,0,0,0],[255,255,255,255]]
  image=footer_ink(footer_raw[text]) if key!='best' else font_style(raw[text],colors,[[255]*4,[255]*4]);add(image,key,text,33 if key!='best' else 8)
 atlas=Image.new('RGBA',(256,64))
 game=ROOT/'assets/race-ui/Race_U/game_image/timg'
 for n in range(13):
  if n<12:
   name=f'tt_d_number_3d_{n:02d}.tpl' if n<10 else 'tt_d_number_3d_coron_00.tpl' if n==10 else 'tt_d_number_3d_coron.tpl'
   p=game/name;source(p);image=decode_tpl(p).resize((24,24),Image.Resampling.LANCZOS)
  else:
   dash=font_style(raw['-'],[[0,0,0,0],[255,224,64,255]],[[255]*4,[255]*4]);image=Image.new('RGBA',(24,24));dash=dash.resize((max(1,round(dash.width*24/dash.height)),24),Image.Resampling.LANCZOS);image.alpha_composite(dash,((24-dash.width)//2,0))
  atlas.alpha_composite(image,(n%8*26+1,n//8*26+1))
 # One texture, thirteen entries: residency deduplicates paths.
 add(atlas,'digit_0')
 for n in range(1,13):rows.append(rows[-1].replace(f'"menu_record_digit_{n-1}"',f'"menu_record_digit_{n}"'))
 (ROOT/'include/mkw/menu_record_text.inc').write_text('// Generated by cook_menu_record_text.py; original BRFNT/footer ink and clock TPLs.\n'+'\n'.join(rows)+'\n')
 assert all(sha(ROOT/p)==digest for p,digest in sources.items())
 (out/'receipt.json').write_text(json.dumps({'sources':sources,'files':files,'footer_style':33,'footer_height':14,'footer_y':222,'transparent_backgrounds':True},indent=2)+'\n')
 print('Staged',len(files),'record textures:',out)
if __name__=='__main__':
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--output',type=Path);cook(p.parse_args().output)
