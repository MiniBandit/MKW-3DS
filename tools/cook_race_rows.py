#!/usr/bin/env python3
"""Cook the race lower screen's standings rows (src/race_bottom_screen.cpp).

Each row is a small box over the full-width map: the menus' selected-button
frame (ui_button_select from tools/cook_menu_ui.py: its gold border), with a
dark see-through inside for the other racers and the frame's own gold fill for
the local player. Inside: the result board's ordinal (1st..12th), the
st_*_32x32 face and the item window icon, at the row's size.

Runs after the menu-ui stage (it reads its button). Outputs
build/race-map/textures/race_bottom_rows.t3x (RGBA8, packed by
resource_manifest.py with the other race_*.t3x) and the generated
include/mkw/race_bottom_rows.hpp.
"""
import argparse
import subprocess
import sys
from pathlib import Path

import numpy as np
from PIL import Image

TOOLS = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOLS))

# Row geometry (lower-screen pixels). Twelve 19 px rows with 1 px of map above and below
# and 0-1 px between them (src/race_bottom_screen.cpp floatRowY).
ROW_H = 19
ORDINAL_H = 12
ICON = 13
ORDINAL_X = 5
INSIDE_ALPHA = 160  # the other racers' dark inside (0..255)
INSIDE_RGB = (10, 12, 14)
BORDER = 4  # the frame's edge as drawn (source corners: 8 px)


def nine_slice(src, width, height, corner=8, drawn=BORDER):
    out = Image.new('RGBA', (width, height))
    sw, sh = src.size
    xs = [(0, corner, 0, drawn), (corner, sw - corner, drawn, width - drawn), (sw - corner, sw, width - drawn, width)]
    ys = [(0, corner, 0, drawn), (corner, sh - corner, drawn, height - drawn), (sh - corner, sh, height - drawn, height)]
    for a0, a1, b0, b1 in xs:
        for e0, e1, f0, f1 in ys:
            if b1 > b0 and f1 > f0:
                out.paste(src.crop((a0, e0, a1, e1)).resize((b1 - b0, f1 - f0), Image.Resampling.LANCZOS), (b0, f0))
    return out


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--root', type=Path, default=TOOLS.parent,
                   help='tree holding assets/race-ui and the menu-ui stage output (default: this repository)')
    p.add_argument('--textures', type=Path, help='output folder for race_bottom_rows.t3x (default: <root>/build/race-map/textures)')
    p.add_argument('--header', type=Path, help='output header (default: <root>/include/mkw/race_bottom_rows.hpp)')
    a = p.parse_args()
    import cook_race_map as maps
    from cook_race_items import decode_tpl, ICONS
    root = a.root.resolve()
    game = root / 'assets/race-ui/Race/game_image'
    maps.UI = root / 'assets/race-ui'
    button = root / 'sd-card/3ds/mkw-3ds/textures/ui_button_select.png'
    if not button.is_file():
        raise SystemExit(f'{button} missing: run tools/cook_menu_ui.py first')
    textures = (a.textures or root / 'build/race-map/textures').resolve()
    header = (a.header or root / 'include/mkw/race_bottom_rows.hpp').resolve()
    textures.mkdir(parents=True, exist_ok=True)

    frame = Image.open(button).convert('RGBA')
    frame = frame.crop(frame.getbbox())
    gold = np.asarray(frame).astype(np.float32)
    dark = gold.copy()
    inside = dark[..., 3] < 160  # the see-through fill; the border is (nearly) opaque
    dark[inside, :3] = INSIDE_RGB
    dark[inside, 3] = INSIDE_ALPHA

    images = {}
    _, ordinals = maps.ordinal_images(ORDINAL_H)
    for i, im in enumerate(ordinals):
        images[('ordinal', i)] = im
    ordinal_w = max(im.width for im in ordinals)
    face_x = ORDINAL_X + ordinal_w + 2
    item_x = face_x + ICON + 2
    row_w = item_x + ICON + 4
    images[('row', 'player')] = nine_slice(Image.fromarray(gold.astype(np.uint8), 'RGBA'), row_w, ROW_H)
    images[('row', 'other')] = nine_slice(Image.fromarray(dark.astype(np.uint8), 'RGBA'), row_w, ROW_H)
    for i, name in enumerate(maps.FACES):
        images[('face', i)] = maps.resize(decode_tpl(game / f'timg/st_{name}_32x32.tpl'), (ICON, ICON))
    for kind, name in ICONS.items():
        images[('item', kind)] = maps.resize(decode_tpl(game / f'timg/{name}.tpl'), (ICON, ICON))
    images[('item', 19)] = maps.resize(decode_tpl(game / 'timg/tt_item_kinoko_2.tpl'), (ICON, ICON))

    for width in (128, 64, 256):
        packed = maps.pack(images, width)
        if packed and packed[0].width * packed[0].height <= 128 * 256:
            break
    else:
        raise SystemExit('race_bottom_rows: the rows no longer fit 128x256')
    atlas, rects = packed
    png = textures / 'race_bottom_rows.png'
    atlas.save(png)
    subprocess.run([maps.TEX3DS, '-f', 'rgba8', '-z', 'none', '-o', str(png.with_suffix('.t3x')), str(png)],
                   check=True, stdout=subprocess.DEVNULL)

    def rect(key):
        if key not in rects:
            return '{0,0,0,0}'
        x, y, w, h = rects[key]
        return f'{{{x},{y},{w},{h}}}'

    def array(keys):
        return '{{' + ','.join(rect(k) for k in keys) + '}}'
    lines = ['// Generated by tools/cook_race_rows.py.', '#pragma once', '#include <array>', '#include <mkw/race_map_assets.hpp>',
             'namespace mkw {',
             '// The standings rows (RGBA8, VRAM): menu button frames (gold border; the local',
             '// player\'s gold fill, the others\' dark see-through inside) and what a row shows.',
             'struct RaceRowsAtlas {',
             '    const char* texture;uint16_t size[2];',
             '    RaceMapRect player,other;',
             '    std::array<RaceMapRect,12> ordinals;  // 1st..12th, result board font',
             '    std::array<RaceMapRect,24> faces;     // st_*_32x32 by retail character id',
             '    std::array<RaceMapRect,21> items;     // by ItemKind; 19 = two Triple Mushrooms left',
             '    uint8_t rowW,rowH,ordinalX,faceX,itemX,icon;',
             '};',
             'inline constexpr RaceRowsAtlas RaceRowsUi{"textures/race_bottom_rows.t3x",'
             f'{{{atlas.width},{atlas.height}}},{rect(("row", "player"))},{rect(("row", "other"))},'
             f'{array([("ordinal", i) for i in range(12)])},{array([("face", i) for i in range(24)])},'
             f'{array([("item", k) for k in range(21)])},{row_w},{ROW_H},{ORDINAL_X},{face_x},{item_x},{ICON}}};',
             '}', '']
    header.parent.mkdir(parents=True, exist_ok=True)
    header.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'race_bottom_rows {atlas.width}x{atlas.height}, row {row_w}x{ROW_H}', flush=True)


if __name__ == '__main__':
    main()
