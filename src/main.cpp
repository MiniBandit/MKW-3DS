        if (fullRace)
            for (unsigned waits = 0; C3D_FrameCounter(0) == lastRefresh && waits < 3; ++waits)
                gspWaitForEvent(GSPGPU_EVENT_VBlank0, false);
        hidScanInput();
        auto held = hidKeysHeld(), down = hidKeysDown();
