                            drawSkinned(accessoryAnimations[i].get(), *accessories[i],
                                        vehicleAnimation.accessory(name,
                                                                   accessoryAnimations[i] &&
                                                                       accessoryAnimations[i]->handleDriveClip() >= 0,
                                                                   instance));
