static void configure(K::System::RaceConfig *config, void *context)
{
    if (replayData)
    {
        config->setGhost(replayData);
        config->raceScenario().players[0].type = K::System::RaceConfig::Player::Type::Ghost;
        return;
    }
    auto &s = config->raceScenario();
    s.course = Courses[courseChoice].id;
    s.engineClass = u8(engineClass);
    s.gameMode=static_cast<decltype(s.gameMode)>(selectedRaceMode);
    s.mirror=selectedMirror;
    s.cpuDifficulty=selectedRaceMode==0?std::min(engineClass,2u):licenseSaves[activeLicense].settings.vsCpu;
    s.cpuVehicles=selectedRaceMode==0?0:licenseSaves[activeLicense].settings.vsVehicles;
    s.itemMode=selectedRaceMode==1?licenseSaves[activeLicense].settings.vsItems:0;
    s.teams=selectedTeams;s.humanTeam=unsigned(selectedHumanTeam);
    if (fullRace)
    {
        static_cast<mkw::RaceGrid *>(context)->configure(*config, driverChoice * mkw::VehiclesPerDriver + vehicleChoice,
                                                         timeTrial ? 1 : 12, selectedRoster.ready?&selectedRoster.choices:nullptr);
        s.players[0].driftIsAuto = automaticDrift;
        return;
    }
    auto &p = s.players[0];
    p.type = K::System::RaceConfig::Player::Type::Local;
    const auto &driver = selectedVehicle();
    p.character = static_cast<K::Character>(driver.character);
    p.vehicle = static_cast<K::Vehicle>(driver.vehicle);
    p.driftIsAuto = false;
}
