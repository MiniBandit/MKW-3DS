// QA captures: a stereo frame also writes its right eye beside the left
// (name.ppm -> name-right.ppm).
static void saveRightEye(mkw::Renderer &renderer, const char *path)
{
    if (!renderer.stereoShown())
        return;
    std::vector<uint8_t> pixels(400 * 240 * 3);
    std::string right(path);
    const auto dot = right.rfind(".ppm");
    if (dot == std::string::npos)
        return;
    right.insert(dot, "-right");
    // Each eye's image must be what its LCD framebuffer received.
    bool presented = renderer.captureTop(pixels.data(), 0) && renderer.presentedMatches(pixels.data(), 0);
    if (renderer.captureTop(pixels.data(), 1))
    {
        presented &= renderer.presentedMatches(pixels.data(), 1);
        if (FILE *f = fopen(right.c_str(), "wb"))
        {
            fprintf(f, "P6\n400 240\n255\n");
            fwrite(pixels.data(), 1, pixels.size(), f);
            fclose(f);
        }
    }
    else
        presented = false;
    if (!presented)
    {
        std::string line = "FAIL stereo presentation ";
        line += path;
        report(line.c_str());
    }
}
// The last race frame as a texture (top row first, 8x8 tiles in Morton order,
// as the lower screen's glyph atlas), drawn behind the pause menu.
static bool snapshotTop(mkw::Renderer &renderer, mkw::Texture &out)
{
    out.reset();
    std::vector<uint8_t> rgb(400 * 240 * 3);
    if (!renderer.captureTop(rgb.data(), 0) || !C3D_TexInit(&out.gpu, 512, 256, GPU_RGB565))
        return false;
    std::vector<uint16_t> texels(512 * 256, 0);
    for (unsigned y = 0; y < 240; ++y)
        for (unsigned x = 0; x < 400; ++x)
        {
            const unsigned ix = x & 7, iy = y & 7;
            const unsigned morton = (ix & 1) | ((iy & 1) << 1) | ((ix & 2) << 1) | ((iy & 2) << 2) | ((ix & 4) << 2) |
                                    ((iy & 4) << 3);
            const uint8_t *p = &rgb[3 * (y * 400 + x)];
            texels[((y / 8) * (512 / 8) + x / 8) * 64 + morton] = uint16_t((p[0] >> 3) << 11 | (p[1] >> 2) << 5 | p[2] >> 3);
        }
    C3D_TexLoadImage(&out.gpu, texels.data(), GPU_TEXFACE_2D, 0);
    C3D_TexFlush(&out.gpu);
    C3D_TexSetFilter(&out.gpu, GPU_NEAREST, GPU_NEAREST);
    C3D_TexSetWrap(&out.gpu, GPU_CLAMP_TO_EDGE, GPU_CLAMP_TO_EDGE);
    out.ready = true;
    return true;
}
// Stereo menus (docs/STEREO_3D.md), Mario Kart 7's garage: the backdrop pane
// (quad 0) at the garage's back wall behind the selection models, enlarged
// about the screen centre by its shift so neither eye bares an edge; the
// models in front of it; the other panes on the screen plane.
static void drawMenuBackdrop(mkw::Renderer &renderer, mkw::MenuRenderer &menuRenderer,
                             const std::vector<mkw::UiQuad> &quads, const mkw::Texture *paused = nullptr)
{
    if (paused && paused->ready)
    {
        // The pause menu over the frozen race, dimmed, instead of the backdrop pane.
        mkw::Renderer::MaterialQuad q{};
        const float u = 400.f / 512.f, v = 240.f / 256.f;
        const float x[4] = {0, 400, 0, 400}, y[4] = {0, 0, 240, 240}, us[4] = {0, u, 0, u}, vs[4] = {0, 0, v, v};
        for (unsigned k = 0; k < 4; ++k)
        {
            q.x[k] = x[k];
            q.y[k] = y[k];
            q.u[k] = us[k];
            q.v[k] = vs[k];
            q.color[k] = 0x8c8c8cffu;
        }
        renderer.drawScreenMaterialQuads(paused, &q, 1, 0x00000000u, 0xffffffffu);
        return;
    }
    const float parallax = mkw::MenuModels::backdropParallax(renderer);
    if (parallax == 0 || quads.empty())
    {
        menuRenderer.draw(renderer, quads, false, 0, 1);
        return;
    }
    static std::vector<mkw::UiQuad> backdrop(1);
    backdrop[0] = quads[0];
    auto &q = backdrop[0];
    if (q.x <= 0 && q.x + q.w >= 400)
    {
        const float grow = (400.f + std::fabs(parallax)) / 400.f;
        q.x = 200.f + (q.x - 200.f) * grow;
        q.y = 120.f + (q.y - 120.f) * grow;
        q.w *= grow;
        q.h *= grow;
    }
    renderer.setScreenDepth(parallax);
    menuRenderer.draw(renderer, backdrop, false, 0, 1);
    renderer.setScreenDepth(renderer.stereoLayer(mkw::stereo::PaneLayer));
}
// Update CIA: the SD card's game files must exist and match this build's
// content stamp. Otherwise explain what to do on the top screen until a key.
// The build version in the lower screen's corner, in the console's 8x8 font,
// until the first race draws that screen. The lower framebuffer is BGR8,
// rotated: w is the screen's height and columns run bottom to top.
static constexpr const char *ProjectUrl = "github.com/MiniBandit/MKW-3DS";
// One line of 8x8 console-font text on the lower screen (BGR8, rotated: w is
// the screen's height and columns run bottom to top).
static void drawText(u8 *framebuffer, u16 w, int left, int top, const char *text, u32 rgb)
{
    const ConsoleFont &font = consoleGetDefault()->font;
    for (int c = 0; text[c] && left + c * 8 + 8 <= 320; ++c)
    {
        const unsigned glyph = u8(text[c]) - font.asciiOffset;
        if (glyph >= font.numChars)
            continue;
        for (int row = 0; row < 8; ++row)
        {
            const u8 bits = font.gfx[glyph * 8 + row];
            for (int col = 0; col < 8; ++col)
                if (bits & (0x80 >> col))
                {
                    const int x = left + c * 8 + col, y = top + row;
                    u8 *p = framebuffer + (size_t(x) * w + (w - 1 - y)) * 3;
                    p[0] = u8(rgb);
                    p[1] = u8(rgb >> 8);
                    p[2] = u8(rgb >> 16);
                }
        }
    }
}
// The build version in the lower screen's corner and, on the first launch of
// a version (install or update), what it adds (WHATS_NEW.txt) and the project
// link, until the first race draws that screen.
static void drawStartScreen(u8 *framebuffer, u16 w, int whatsNew)
{
    char text[48];
    snprintf(text, sizeof text, "v%s%s", MKW_VERSION, kQa ? " (test)" : "");
    drawText(framebuffer, w, 320 - 4 - 8 * int(std::strlen(text)), 240 - 12, text, 0x909090);
    if (!whatsNew)
        return;
    int y = 12;
    snprintf(text, sizeof text, whatsNew == 2 ? "Updated to v%s" : "Mario Kart Wii 3DS v%s", MKW_VERSION);
    drawText(framebuffer, w, 16, y, text, 0xffd040);
    y += 12;
    if (MKW_QUICK_UPDATE)
    {
        drawText(framebuffer, w, 16, y, "Quick update: no rebuild needed.", 0xffffff);
        y += 10;
        drawText(framebuffer, w, 16, y, "Your game files stay as they are.", 0xffffff);
        y += 16;
    }
    else
        y += 4;
    drawText(framebuffer, w, 16, y, "What's new:", 0xffd040);
    y += 12;
    const char *line = MKW_WHATS_NEW;
    while (*line && y < 240 - 52)
    {
        const char *end = std::strchr(line, '\n');
        const size_t n = end ? size_t(end - line) : std::strlen(line);
        char buffer[40];
        snprintf(buffer, sizeof buffer, "%.*s", int(std::min<size_t>(n, 38)), line);
        drawText(framebuffer, w, 16, y, buffer, 0xd0d0d0);
        y += 10;
        line += n;
        if (*line == '\n')
            ++line;
    }
    drawText(framebuffer, w, 16, 240 - 40, "This message only shows once.", 0x909090);
    drawText(framebuffer, w, 16, 240 - 26, ProjectUrl, 0x60a0ff);
}
// The first launch of each version, a first install included: the SD card
// records the version that last ran, so later launches match it and stay quiet.
// Returns 0 when already seen, 1 for a first install, 2 for an update (another
// version recorded, or a quick update, which always replaces an older one).
static int firstLaunchOfVersion()
{
    char seen[32] = {};
    if (FILE *f = fopen("sdmc:/3ds/mkw-3ds/last-version.txt", "r"))
    {
        if (!fgets(seen, sizeof seen, f))
            seen[0] = 0;
        fclose(f);
    }
    seen[strcspn(seen, "\r\n")] = 0;
    if (!strcmp(seen, MKW_VERSION))
        return 0;
    mkdir("sdmc:/3ds", 0777);
    mkdir("sdmc:/3ds/mkw-3ds", 0777);
    if (FILE *f = fopen("sdmc:/3ds/mkw-3ds/last-version.txt", "w"))
    {
        fprintf(f, "%s\n", MKW_VERSION);
        fclose(f);
    }
    return seen[0] || MKW_QUICK_UPDATE ? 2 : 1;
}
// The content stamp beside a copy of the game files (empty when absent).
static void readContent(const char *root, char (&found)[80])
{
    found[0] = 0;
    char path[64];
    snprintf(path, sizeof path, "%scontent.txt", root);
    if (FILE *f = fopen(path, "r"))
    {
        if (!fgets(found, sizeof found, f))
            found[0] = 0;
        fclose(f);
    }
    found[strcspn(found, "\r\n")] = 0;
}
static bool contentMatches(const char *root)
{
    char found[80];
    readContent(root, found);
    char common[64];
    snprintf(common, sizeof common, "%sRace/Common.szs", root);
    return (!strcmp(found, MKW_CONTENT) || !strcmp(found, MKW_CONTENT_WINDOWS_LEGACY)) && exists(common);
}
